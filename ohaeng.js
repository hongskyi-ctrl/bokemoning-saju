// 사주팔자의 오행 개수 계산
function countElements(saju) {
    const counts = {
        "목": 0,
        "화": 0,
        "토": 0,
        "금": 0,
        "수": 0
    };

    const pillars = [
        saju.year,
        saju.month,
        saju.day,
            ...(saju.time === "출생 시간 미상" ? [] : [saju.time])
    ];

    for (const pillar of pillars) {
        for (const char of pillar) {
            const element = elementMap[char];

            if (element) {
                counts[element]++;
            }
        }
    }

    return counts;
}

window.countElements = countElements;

